	/**
	 * Looks a block up the way {@code Character.UnicodeBlock.forName} does.
	 *
	 * @param name the name as written after {@code In} or {@code block=}
	 * @return the first and last code unit, or null when no such block is held here
	 */
	static int[] find(String name) {
		String key = name.toUpperCase(Locale.ROOT);
		for (String entry : TABLE) {
			int end = entry.indexOf(' ', 5);
			if (!hasName(entry, end + 1, key)) continue;
			return new int[] {
				Integer.parseInt(entry.substring(0, 4), 16),
				Integer.parseInt(entry.substring(5, 9), 16)
			};
		}
		return null;
	}

	/** Whether the names that start at {@code from} include {@code key}. */
	private static boolean hasName(String entry, int from, String key) {
		int start = from;
		while (start <= entry.length()) {
			int bar = entry.indexOf('|', start);
			int stop = bar < 0 ? entry.length() : bar;
			if (stop - start == key.length() && entry.startsWith(key, start)) return true;
			start = stop + 1;
		}
		return false;
	}
